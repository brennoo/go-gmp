#!/bin/sh
# Brings up gvmd (and its minimum dependency set) from hack/docker-compose.yml,
# generates TLS certificates on first run, and creates/resets the admin user.
#
# Usage:
#   hack/gvmd-up.sh
#   SCAN_DATA=1 hack/gvmd-up.sh          # also start vulnerability-tests
#   GVMD_ADMIN_PASSWORD=... hack/gvmd-up.sh
#
# See hack/README.md and CONTRIBUTING.md for the full manual-testing story.
set -eu

. "$(dirname "$0")/compose-lib.sh"

# Everything below addresses paths through $HACK_DIR rather than a working
# directory, so the script runs correctly from anywhere.
CA_DIR="$HACK_DIR/CA"

# The admin password is never hardcoded silently: it comes from an env var,
# and falling back to the documented default is logged so it is never a
# surprise in a transcript.
if [ -z "${GVMD_ADMIN_PASSWORD:-}" ]; then
	GVMD_ADMIN_PASSWORD="admin"
	log "GVMD_ADMIN_PASSWORD not set; using the documented default 'admin'."
	log "This is fine for a throwaway local stack; set the env var for anything else."
fi

# The setting UUID gvmd uses for "feed import owner". Fixed across gvmd
# versions; not a resource ID this script creates.
FEED_OWNER_SETTING_UUID="78eceaec-3385-11ea-b237-28d24461215b"

users_file="$(mktemp)"
trap 'rm -f "$users_file"' EXIT

# --- 1. Certificates --------------------------------------------------------
#
# Deliberately NOT the `docker-compose exec -it gvmd gvm-manage-certs -af`
# sequence from the old hack/README.md: that races gvmd's `restart:
# on-failure` and requires a full first boot before you can exec into the
# container at all. A throwaway container skips both problems; --no-deps
# means only gvmd's image is used, none of postgres or the five data loaders
# start, and the CA bind mounts still apply so the PEMs land on the host.
if [ -f "$CA_DIR/cacert.pem" ]; then
	log "$CA_DIR/cacert.pem already present; skipping certificate generation."
else
	log "No $CA_DIR/cacert.pem found; generating certificates with gvm-manage-certs."

	# UNCONFIRMED (verify by actually running this script): gvmd runs as uid
	# `gvmd` inside the container and must be able to read its own generated
	# private key. If the compose `run` below (which uses the image's
	# default user) leaves CA/private/*.pem root-owned and 0600, gvmd will
	# fail to start with a permission error visible in its container logs.
	# If that happens, re-run as:
	#
	#   rm -rf hack/CA && GVMD_FIX_CERT_OWNERSHIP=1 hack/gvmd-up.sh
	#
	# which generates the certs as the current host user instead, and the
	# chmod below then makes them world-readable so gvmd's uid can read them
	# regardless of exactly what uid that is inside the container.
	if [ "${GVMD_FIX_CERT_OWNERSHIP:-0}" = "1" ]; then
		log "GVMD_FIX_CERT_OWNERSHIP=1: generating certs as $(id -u):$(id -g) instead of the image default."
		dc run --rm --no-deps --user "$(id -u):$(id -g)" \
			--entrypoint gvm-manage-certs gvmd -af
	else
		dc run --rm --no-deps \
			--entrypoint gvm-manage-certs gvmd -af
	fi
	# gvmd runs as uid `gvmd` inside the container and has to read the server
	# key, which lands here owned by whoever generated it. Rather than guess
	# that uid, make the tree readable.
	#
	# This does mean CA/private/*.pem ends up world-readable on the host. That
	# is acceptable only because these are throwaway certificates for a local
	# development stack, regenerated by deleting hack/CA — they are gitignored
	# and must never be reused anywhere real. Do not copy this pattern.
	chmod -R a+rX "$CA_DIR" 2>/dev/null || true
fi

# --- 2. Bring up gvmd ---------------------------------------------------
#
# gvmd's own `depends_on` in hack/docker-compose.yml already names the
# minimum set: pg-gvm plus the five one-shot data loaders. Nothing
# scanner-side starts unless asked for below.
#
# SCAN_DATA=1 starts ospd-openvas, not just vulnerability-tests: gvmd polls
# ospd-openvas over /run/ospd/ospd-openvas.sock for the NVT feed's version,
# and until that socket exists get_feeds reports an empty-named feed with no
# version forever. vulnerability-tests only seeds the raw VT data files onto
# the shared volume; it is ospd-openvas that reads them and answers gvmd's
# osp_scanner_feed_version query. Compose's depends_on still starts
# vulnerability-tests (and redis-server, gpg-data, configure-openvas) first,
# so naming ospd-openvas here is sufficient.
if [ "${SCAN_DATA:-0}" = "1" ]; then
	log "SCAN_DATA=1: also starting ospd-openvas (and its vulnerability-tests/redis-server/gpg-data/configure-openvas dependencies), needed for get_feeds to ever report the NVT feed ready, and for get_nvts to return anything."
	dc up -d gvmd ospd-openvas
else
	dc up -d gvmd
fi

# --- 3. Wait for gvmd's administrative CLI, not the GMP TLS listener -------
#
# There are no healthchecks in the compose file. `gvmd --get-users` talks
# directly to Postgres and becomes responsive once gvmd has finished its own
# database setup, which is unrelated to (and much faster than) the 20-45
# minute feed sync that the Go readiness ladder in internal/gmptest/live.go
# waits for separately.
log "Waiting for gvmd's administrative CLI to become responsive..."
attempt=0
max_attempts=30
while ! dc exec -T -u gvmd gvmd gvmd --get-users >"$users_file" 2>/dev/null; do
	attempt=$((attempt + 1))
	if [ "$attempt" -ge "$max_attempts" ]; then
		log "gvmd's CLI did not respond after $((max_attempts * 10))s."
		log "Inspect the container logs with: $COMPOSE_CMD -f $COMPOSE_FILE logs gvmd"
		exit 1
	fi
	sleep 10
done

# --- 4. Create-or-reset the admin user, idempotently ------------------------
#
# --create-user fails if the user already exists (a warm volume);
# --user/--new-password fails if it does not exist yet (a cold volume). This
# probes first with --get-users so both cases run something that succeeds.
if grep -qx admin "$users_file"; then
	log "User 'admin' already exists."
else
	log "Creating user 'admin'."
	dc exec -T -u gvmd gvmd gvmd --create-user=admin
fi
dc exec -T -u gvmd gvmd gvmd --user=admin --new-password="$GVMD_ADMIN_PASSWORD"

# --- 5. Feed import owner ---------------------------------------------------
#
# Never set anywhere else in this stack. Without it, get_configs,
# get_port_lists, get_report_formats and get_scanners all silently return
# empty, which is the single most commonly missed step in a Greenbone
# bring-up.
admin_uuid="$(dc exec -T -u gvmd gvmd gvmd --get-users --verbose | awk '$1 == "admin" { print $2 }')"
if [ -z "$admin_uuid" ]; then
	log "Could not determine admin's UUID from 'gvmd --get-users --verbose'; feed import owner was NOT set."
	exit 1
fi
dc exec -T -u gvmd gvmd gvmd --modify-setting "$FEED_OWNER_SETTING_UUID" --value "$admin_uuid"
log "Feed import owner set to 'admin' ($admin_uuid)."

log ""
log "gvmd is up. Feed sync (SCAP/CERT/NVT data) runs in the background and"
log "takes 20-45 minutes on a first boot; internal/gmptest's readiness ladder"
log "polls get_feeds and blocks until it is done. Without SCAN_DATA=1, the NVT"
log "feed never gets a version (ospd-openvas never started to report one), so"
log "get_feeds — and the readiness ladder — waits the full budget and never"
log "succeeds."
log ""
# gvm-manage-certs sets the server certificate's CN but does not give it any
# Subject Alternative Names. Confirmed empirically (not just suspected): Go's
# crypto/x509 refuses to fall back to CN for hostname verification on a
# SAN-less certificate ("certificate relies on legacy Common Name field, use
# SANs instead"), so -gmp.servername=<CN> cannot ever pass verification
# against this cert, no matter how the CN was obtained. -gmp.insecure is the
# only option that works against this locally generated, throwaway CA.
log "Next steps:"
log "  Run the integration suite:"
log "    go test -tags integration ./internal/gmptest/... \\"
log "      -gmp.pass=\"$GVMD_ADMIN_PASSWORD\" -gmp.insecure"
log ""
log "To stop: hack/gvmd-down.sh (add --purge to also delete the data"
log "volumes, which throws away this boot's feed sync)."
