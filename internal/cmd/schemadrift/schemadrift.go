// defaultSourceRepository identifies gvmd's entry in the mirror lock file —
// the one image this command ever resolves or boots, since T-17 only cares
// about gvmd's served schema.
const defaultSourceRepository = "registry.community.greenbone.net/community/gvmd"

// dialOptions mirrors internal/codegen/snapshot_live_test.go's -gmp.* flags,
// reimplemented here because that helper is test-only and build-tagged
// integration.
type dialOptions struct {
	addr, user, pass, caFile, serverName string
	insecure                             bool
}

type dialFunc func(ctx context.Context, opts dialOptions) (gmp.Connection, error)

type imageDigestFunc func(ctx context.Context, composeFile, service string) (string, error)

// dialLive authenticates against a live gvmd and returns the connection,
// which the caller must Close. See dialOptions.insecure's flag help for why
// hack/gvmd-up.sh's own certificates can never satisfy -gmp.servername.
func dialLive(ctx context.Context, opts dialOptions) (gmp.Connection, error) {
	var tlsOpts []connections.TLSOption
	if opts.insecure {
		tlsOpts = []connections.TLSOption{connections.WithInsecureSkipVerify()}
	} else {
		if opts.serverName == "" {
			return nil, fmt.Errorf("-gmp.servername is required unless -gmp.insecure is set")
		}
		tlsOpts = []connections.TLSOption{
			connections.WithRootCAFile(opts.caFile),
			connections.WithServerName(opts.serverName),
		}
	}

	conn, err := connections.NewTLSConnection(ctx, opts.addr, tlsOpts...)
	if err != nil {
		return nil, fmt.Errorf("dialing gvmd: %w", err)
	}

	cli := client.New(conn)
	creds := &commands.AuthenticateCredentials{Username: opts.user, Password: opts.pass}
	if _, err := cli.Authenticate(ctx, &commands.Authenticate{Credentials: creds}); err != nil {
		_ = conn.Close()
		return nil, fmt.Errorf("authenticating: %w", err)
	}
	return conn, nil
}

// findLockEntry returns the lock file entry identifying gvmd, the only image
// this command ever inspects.
func findLockEntry(lockFile, sourceRepository string) (mirror.LockEntry, error) {
	lock, err := mirror.ReadLock(lockFile)
	if err != nil {
		return mirror.LockEntry{}, fmt.Errorf("reading lock file %s: %w", lockFile, err)
	}
	for _, e := range lock.Entries {
		if e.SourceRepository == sourceRepository {
			return e, nil
		}
	}
	return mirror.LockEntry{}, fmt.Errorf("lock file %s has no entry for source repository %q", lockFile, sourceRepository)
}

// digestHex returns the sha256 hex suffix of a "repo@sha256:hex" reference,
// so two refs pointing at the same content but different repositories (the
// upstream registry vs. this project's GHCR mirror) can be compared by
// content rather than by string equality of the whole ref.
func digestHex(ref string) (string, bool) {
	_, hex, ok := strings.Cut(ref, "@sha256:")
	return hex, ok && hex != ""
}

// flags is schemadrift's parsed command line, split out of run so each mode
// function takes only what it needs instead of a flag.FlagSet.
type flags struct {
	resolveOnly      bool
	lockFile         string
	sourceRepository string
	manifestFile     string
	schemaDir        string
	composeFile      string
	dial             dialOptions
}

func parseFlags(args []string) (flags, error) {
	fs := flag.NewFlagSet("schemadrift", flag.ContinueOnError)
	var f flags
	fs.BoolVar(&f.resolveOnly, "resolve-only", false,
		"print the current upstream digest for -source-repository and exit; does not dial gvmd or write anything")
	fs.StringVar(&f.lockFile, "lock-file", "hack/image-mirror.lock.json",
		"the mirror lock file gvmd's upstream channel and currently pinned digest are read from")
	fs.StringVar(&f.sourceRepository, "source-repository", defaultSourceRepository,
		"the lock file entry's source_repository identifying gvmd")
	fs.StringVar(&f.manifestFile, "manifest", "internal/codegen/manifest.json", "the generation manifest")
	fs.StringVar(&f.schemaDir, "schema", "internal/codegen/testdata/schema", "the committed schema snapshots to diff the served schema against")
	fs.StringVar(&f.dial.addr, "gmp.addr", "127.0.0.1:9390", "host:port of gvmd's GMP TLS listener")
	fs.StringVar(&f.dial.user, "gmp.user", "admin", "GMP username, as created by hack/gvmd-up.sh")
	fs.StringVar(&f.dial.pass, "gmp.pass", "admin", "GMP password; matches hack/gvmd-up.sh's documented default")
	fs.StringVar(&f.dial.caFile, "gmp.cafile", "hack/CA/cacert.pem", "path to the CA certificate generated by gvm-manage-certs")
	fs.StringVar(&f.dial.serverName, "gmp.servername", "",
		"CN of gvmd's TLS server certificate, required unless -gmp.insecure is set")
	fs.BoolVar(&f.dial.insecure, "gmp.insecure", false,
		"skip TLS certificate verification instead of using -gmp.cafile/-gmp.servername; never the default, opt in explicitly")
	fs.StringVar(&f.composeFile, "live.compose-file", "hack/docker-compose.yml",
		"path to the Compose file backing the live gvmd, used to resolve its served image digest")
	if err := fs.Parse(args); err != nil {
		return flags{}, err
	}
	if fs.NArg() > 0 {
		return flags{}, fmt.Errorf("unexpected argument %q; schemadrift takes flags only", fs.Arg(0))
	}
	return f, nil
}

// run resolves gvmd's lock entry and either prints its current upstream
// digest (-resolve-only, used to pick which image a candidate stack should
// boot) or dials the already-running candidate stack, extracts its served
// schema, and reports drift against the committed snapshots.
func run(ctx context.Context, args []string, runner mirror.Runner, dial dialFunc, imageDigest imageDigestFunc, stdout, _ io.Writer) error {
	f, err := parseFlags(args)
	if err != nil {
		return err
	}

	entry, err := findLockEntry(f.lockFile, f.sourceRepository)
	if err != nil {
		return err
	}

	if f.resolveOnly {
		return runResolveOnly(ctx, runner, entry, stdout)
	}
	return runReport(ctx, f, dial, imageDigest, entry, stdout)
}

// runResolveOnly prints entry's fresh upstream digest, resolved from its
// SourceChannel — used to pick which image a candidate stack should boot,
// never the currently pinned one (see docs/review-2026-08.md, T-17, on why
// diffing against the pinned image would never show drift).
func runResolveOnly(ctx context.Context, runner mirror.Runner, entry mirror.LockEntry, stdout io.Writer) error {
	if _, err := exec.LookPath("skopeo"); err != nil {
		return fmt.Errorf("skopeo not found in PATH: %w", err)
	}
	digest, err := mirror.ResolveDigest(ctx, runner, entry.SourceChannel)
	if err != nil {
		return err
	}
	_, err = fmt.Fprintln(stdout, digest)
	return err
}

// runReport dials the already-running candidate stack, extracts its served
// schema, and reports drift against the committed snapshots.
func runReport(ctx context.Context, f flags, dial dialFunc, imageDigest imageDigestFunc, entry mirror.LockEntry, stdout io.Writer) error {
	conn, err := dial(ctx, f.dial)
	if err != nil {
		return err
	}
	defer conn.Close() //nolint:errcheck // best-effort cleanup; the report's own errors take precedence

	servedDigest, err := imageDigest(ctx, f.composeFile, "gvmd")
	if err != nil {
		return fmt.Errorf("resolving gvmd's served image digest: %w", err)
	}

	raw, err := conn.RawXML(ctx, `<help format="XML" type=""/>`)
	if err != nil {
		return fmt.Errorf("<help>: %w", err)
	}

	cmds, err := schema.LoadServed([]byte(raw), servedDigest)
	if err != nil {
		return fmt.Errorf("parsing served schema: %w", err)
	}

	m, err := codegen.LoadManifest(f.manifestFile)
	if err != nil {
		return fmt.Errorf("loading manifest %s: %w", f.manifestFile, err)
	}

	report, err := codegen.DetectDrift(cmds, m, f.schemaDir)
	if err != nil {
		return fmt.Errorf("detecting drift: %w", err)
	}

	return writeReport(stdout, entry.DestinationDigest, servedDigest, report)
}

func writeReport(stdout io.Writer, pinnedDigest, servedDigest string, report codegen.DriftReport) error {
	movedMsg := "upstream has moved since the last mirror run."
	if pinnedHex, ok1 := digestHex(pinnedDigest); ok1 {
		if servedHex, ok2 := digestHex(servedDigest); ok2 && pinnedHex == servedHex {
			movedMsg = "upstream has not moved since the last mirror run."
		}
	}

	_, err := fmt.Fprintf(stdout, "pinned:  %s\nserved:  %s\n%s\n\n%s", pinnedDigest, servedDigest, movedMsg, report.String())
	return err
}
