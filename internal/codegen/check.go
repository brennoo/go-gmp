// GeneratedMarker is the first line every file Generate emits carries. It is
// the only way to tell a generator-owned file in the output directory from a
// hand-written neighbour, which is what makes the "obsolete" category
// decidable: commands/ holds 118 hand-written files that must never be
// reported.
const GeneratedMarker = "// Code generated by internal/codegen. DO NOT EDIT."

// Report is what CheckOutput found. Every field is a sorted list of paths
// (relative to whatever outDir was passed), except MalformedSnapshots, whose
// entries are "command: reason".
type Report struct {
	// Missing is a file the manifest and schema say should exist in outDir
	// but does not.
	Missing []string
	// Modified is a file that exists in outDir but whose bytes differ from
	// what the generator produces right now.
	Modified []string
	// Obsolete is a generator-owned file in outDir that nothing in the
	// manifest accounts for: a leftover from a command or family that used
	// to be generated.
	Obsolete []string
	// MalformedSnapshots is a command the manifest names whose Stage-A JSON
	// is absent or does not parse.
	MalformedSnapshots []string
}

// OK reports whether every category is empty.
func (r Report) OK() bool {
	return len(r.Missing) == 0 && len(r.Modified) == 0 && len(r.Obsolete) == 0 && len(r.MalformedSnapshots) == 0
}

// String renders the report for a terminal, omitting empty categories.
func (r Report) String() string {
	var b strings.Builder
	section := func(title string, items []string) {
		if len(items) == 0 {
			return
		}
		fmt.Fprintf(&b, "%s (%d):\n", title, len(items))
		for _, it := range items {
			fmt.Fprintf(&b, "  %s\n", it)
		}
	}
	section("missing", r.Missing)
	section("modified", r.Modified)
	section("obsolete", r.Obsolete)
	section("malformed or missing snapshots", r.MalformedSnapshots)
	return b.String()
}

// CheckOutput compares the already-committed generated files in outDir against
// what the manifest and the Stage-A snapshots in schemaDir say they should be.
//
// It is strictly read-only: nothing under outDir is created, changed or
// removed, no temporary directory is used (generated source is compared in
// memory against os.ReadFile of the committed file), and git is never
// consulted, so the answer is the same on a clean tree, a dirty tree, or a
// checkout with no .git at all.
//
// An error return means the check could not be run (an unreadable output
// directory, a manifest whose family names disagree with the generator's
// naming convention). A problem with the generated tree itself comes back as a
// populated Report with a nil error — that is the expected failure mode, and it
// is the caller's job to turn a non-OK report into a non-zero exit status.
//
// Review-only families (Family.ReviewOnly) are outside its scope entirely:
// their output lives in testdata/golden, not outDir, so checking them here
// would report every one of their still-hand-written files as stale.
func CheckOutput(m Manifest, schemaDir, outDir string, ov map[string]Override) (Report, error) {
	var r Report
	m = m.Adopted()

	generated, skipped := map[string]string{}, map[string]bool{}
	from := map[string]string{}
	for _, f := range m.Families {
		cmds, bad := loadFamilySnapshots(m, schemaDir, f)
		if len(bad) > 0 {
			// A family whose input is broken cannot be generated, so its
			// files are neither checked nor reported obsolete: the snapshot
			// problem is the finding, and burying it under a pile of
			// derived ones would only obscure it.
			r.MalformedSnapshots = append(r.MalformedSnapshots, bad...)
			skipped[f.Name] = true
			continue
		}
		files, err := Generate(cmds, ov)
		if err != nil {
			return Report{}, fmt.Errorf("codegen: family %q: %w", f.Name, err)
		}
		if err := mergeFamilyFiles(generated, from, f, files); err != nil {
			return Report{}, err
		}
	}

	for name, src := range generated {
		path := filepath.Join(outDir, name)
		committed, err := os.ReadFile(path) //nolint:gosec // outDir is an operator-supplied directory to inspect
		switch {
		case os.IsNotExist(err):
			r.Missing = append(r.Missing, path)
		case err != nil:
			return Report{}, fmt.Errorf("codegen: reading %s: %w", path, err)
		case string(committed) != src:
			r.Modified = append(r.Modified, path)
		}
	}

	obsolete, err := findObsolete(m, outDir, generated, skipped)
	if err != nil {
		return Report{}, err
	}
	r.Obsolete = obsolete

	sort.Strings(r.Missing)
	sort.Strings(r.Modified)
	sort.Strings(r.MalformedSnapshots)
	return r, nil
}

// loadFamilySnapshots reads one family's snapshots, returning a "command:
// reason" line for each one that is absent or unparseable instead of failing
// on the first. Reporting all of them at once is the difference between one
// fix-and-rerun cycle and one per broken file.
func loadFamilySnapshots(m Manifest, schemaDir string, f Family) (cmds []schema.Command, bad []string) {
	for _, name := range f.Commands {
		path := m.SnapshotPath(schemaDir, name)
		data, err := os.ReadFile(path) //nolint:gosec // schemaDir is an operator-supplied snapshot directory
		if err != nil {
			bad = append(bad, fmt.Sprintf("%s: %v (run the snapshot test with -update)", name, err))
			continue
		}
		var c schema.Command
		if err := json.Unmarshal(data, &c); err != nil {
			bad = append(bad, fmt.Sprintf("%s: %s: %v", name, path, err))
			continue
		}
		if c.Name != name {
			bad = append(bad, fmt.Sprintf("%s: %s declares command %q", name, path, c.Name))
			continue
		}
		cmds = append(cmds, c)
	}
	return cmds, bad
}

// findObsolete lists the generator-owned files in outDir that the current
// manifest no longer produces.
//
// The scan is non-recursive: everything Generate emits lands directly in
// outDir. Files belonging to a family skipped for a bad snapshot are exempt —
// they are not stale, their input is simply unreadable right now.
func findObsolete(m Manifest, outDir string, generated map[string]string, skipped map[string]bool) ([]string, error) {
	exempt := map[string]bool{}
	for _, f := range m.Families {
		if !skipped[f.Name] {
			continue
		}
		exempt[f.SharedFile()] = true
		for _, c := range f.Commands {
			exempt[CommandFile(c)] = true
		}
	}

	entries, err := os.ReadDir(outDir)
	if err != nil {
		return nil, fmt.Errorf("codegen: reading %s: %w", outDir, err)
	}
	var out []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") {
			continue
		}
		if _, ok := generated[name]; ok || exempt[name] {
			continue
		}
		path := filepath.Join(outDir, name)
		marked, err := hasGeneratedMarker(path)
		if err != nil {
			return nil, err
		}
		if marked {
			out = append(out, path)
		}
	}
	sort.Strings(out)
	return out, nil
}

// hasGeneratedMarker reports whether path's first line is GeneratedMarker.
func hasGeneratedMarker(path string) (bool, error) {
	data, err := os.ReadFile(path) //nolint:gosec // a path enumerated from the operator-supplied outDir
	if err != nil {
		return false, fmt.Errorf("codegen: reading %s: %w", path, err)
	}
	line, _, _ := strings.Cut(string(data), "\n")
	return strings.TrimRight(line, "\r") == GeneratedMarker, nil
}
