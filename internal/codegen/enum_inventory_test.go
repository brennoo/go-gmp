// enumInventoryFile is T-19's API-impact golden: one row per generated enum
// type, so the whole surface a family adoption or a generator change touches
// is reviewable in one diff instead of read out of commands/*.go by hand.
const enumInventoryFile = "testdata/ENUM_INVENTORY.md"

// enumInventoryRow is one generated enum type, extracted from the real
// output of emitEnum rather than re-derived by a second, independent
// collection/naming pass: parsing the actual generated bytes can never
// disagree with what commands/*.go really contains.
type enumInventoryRow struct {
	GoName   string
	WireName string
	Owner    string
	File     string
	Consts   []string // "GoConstName = \"value\"", in declaration order
}

// enumDocRE matches emitEnum's doc comment exactly (see generate.go); a
// generated `type X string` whose comment doesn't match is a generator bug,
// not a row to silently skip.
var enumDocRE = regexp.MustCompile(`^(\w+) is the <([^>]+)> value of (.+)\. See the GMP protocol docs for details\.$`)

// TestEnumInventory builds and checks the enum inventory golden. Regenerate
// with: go test ./internal/codegen -run TestEnumInventory -update
func TestEnumInventory(t *testing.T) {
	got := generateOrFail(t)

	names := make([]string, 0, len(got))
	for name := range got {
		names = append(names, name)
	}
	sort.Strings(names)

	var rows []enumInventoryRow
	for _, name := range names {
		rs, err := extractEnumRows(name, got[name])
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		rows = append(rows, rs...)
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].GoName < rows[j].GoName })

	doc := renderEnumInventory(rows)

	if *update {
		if err := os.WriteFile(enumInventoryFile, []byte(doc), 0o600); err != nil {
			t.Fatalf("Failed to write %s: %v", enumInventoryFile, err)
		}
		return
	}

	want, err := os.ReadFile(enumInventoryFile) //nolint:gosec // a fixed testdata path
	if err != nil {
		t.Fatalf("No committed enum inventory (%v).\nRun with -update to create it.", err)
	}
	if doc != string(want) {
		t.Fatalf("%s changed. Re-run with -update and review the diff.\n"+
			"committed %d bytes, now %d bytes\n%s",
			enumInventoryFile, len(want), len(doc), firstDiff(string(want), doc))
	}
}

// TestEnumInventoryIsDeterministic guards the golden's only real
// precondition: building it twice from the same input produces byte-identical
// output, the same guarantee TestGenerateIsDeterministic gives the goldens
// this inventory is derived from.
func TestEnumInventoryIsDeterministic(t *testing.T) {
	got := generateOrFail(t)
	build := func() string {
		var rows []enumInventoryRow
		for name, src := range got {
			rs, err := extractEnumRows(name, src)
			if err != nil {
				t.Fatalf("%s: %v", name, err)
			}
			rows = append(rows, rs...)
		}
		sort.Slice(rows, func(i, j int) bool { return rows[i].GoName < rows[j].GoName })
		return renderEnumInventory(rows)
	}
	a, b := build(), build()
	if a != b {
		t.Fatalf("Building the enum inventory twice from the same input produced different output:\n%s", firstDiff(a, b))
	}
}

// extractEnumRows parses one generated file and returns one row per
// `type X string` + `const (...)` pair emitEnum wrote — the only place the
// generator emits a named string type (see generate.go's emitEnum).
func extractEnumRows(file, src string) ([]enumInventoryRow, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}

	var rows []enumInventoryRow
	for i, decl := range f.Decls {
		gd, ts, ok := enumTypeDecl(decl)
		if !ok {
			continue
		}
		wire, owner, err := enumDoc(file, gd, ts.Name.Name)
		if err != nil {
			return nil, err
		}
		consts, err := enumConstBlock(file, f.Decls, i, ts.Name.Name)
		if err != nil {
			return nil, err
		}
		rows = append(rows, enumInventoryRow{GoName: ts.Name.Name, WireName: wire, Owner: owner, File: file, Consts: consts})
	}
	return rows, nil
}

// enumTypeDecl reports whether decl is a `type X string` declaration.
func enumTypeDecl(decl ast.Decl) (*ast.GenDecl, *ast.TypeSpec, bool) {
	gd, ok := decl.(*ast.GenDecl)
	if !ok || gd.Tok != token.TYPE || len(gd.Specs) != 1 {
		return nil, nil, false
	}
	ts, ok := gd.Specs[0].(*ast.TypeSpec)
	if !ok {
		return nil, nil, false
	}
	id, ok := ts.Type.(*ast.Ident)
	if !ok || id.Name != "string" {
		return nil, nil, false
	}
	return gd, ts, true
}

// enumDoc validates gd's doc comment against emitEnum's format and extracts
// the wire name and owning command(s) it records.
func enumDoc(file string, gd *ast.GenDecl, typeName string) (wire, owner string, err error) {
	// Every named-string type the generator emits is an enum (see
	// emitEnum's doc comment): there is exactly one call site.
	if gd.Doc == nil {
		return "", "", fmt.Errorf("%s: %q has no doc comment", file, typeName)
	}
	doc := strings.TrimSpace(gd.Doc.Text())
	m := enumDocRE.FindStringSubmatch(doc)
	if m == nil {
		return "", "", fmt.Errorf("%s: %q's doc comment %q does not match emitEnum's format", file, typeName, doc)
	}
	if m[1] != typeName {
		return "", "", fmt.Errorf("%s: doc comment names %q but the type is %q", file, m[1], typeName)
	}
	return m[2], m[3], nil
}

// enumConstBlock parses the const block immediately following decls[i] (the
// enum's type declaration) into "GoConstName = \"value\"" strings, in order.
func enumConstBlock(file string, decls []ast.Decl, i int, typeName string) ([]string, error) {
	if i+1 >= len(decls) {
		return nil, fmt.Errorf("%s: %q has no following const block", file, typeName)
	}
	cd, ok := decls[i+1].(*ast.GenDecl)
	if !ok || cd.Tok != token.CONST {
		return nil, fmt.Errorf("%s: %q is not immediately followed by a const block", file, typeName)
	}

	var consts []string
	for _, spec := range cd.Specs {
		vs, ok := spec.(*ast.ValueSpec)
		if !ok || len(vs.Names) != 1 || len(vs.Values) != 1 {
			return nil, fmt.Errorf("%s: %q's const block has an unexpected shape", file, typeName)
		}
		typeID, ok := vs.Type.(*ast.Ident)
		if !ok || typeID.Name != typeName {
			return nil, fmt.Errorf("%s: %q's const block declares a value of the wrong type", file, typeName)
		}
		lit, ok := vs.Values[0].(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return nil, fmt.Errorf("%s: %q's const block has a non-string value", file, typeName)
		}
		value, err := strconv.Unquote(lit.Value)
		if err != nil {
			return nil, fmt.Errorf("%s: %q: %w", file, typeName, err)
		}
		consts = append(consts, fmt.Sprintf("%s = %q", vs.Names[0].Name, value))
	}
	return consts, nil
}

// renderEnumInventory renders the inventory deterministically: sorted by Go
// type name, with nothing environment-dependent in the output.
func renderEnumInventory(rows []enumInventoryRow) string {
	var b strings.Builder
	b.WriteString(`# Enum field inventory

Regenerate with: go test ./internal/codegen -run TestEnumInventory -update

T-19: every generated named string type for an <alts>-constrained field, with
its wire name, the command(s) it belongs to, and its ordered constants —
extracted directly from the generated commands/*.go bytes so this can never
disagree with what is actually committed.

`)
	fmt.Fprintf(&b, "total enum types: %d\n\n", len(rows))
	for _, r := range rows {
		fmt.Fprintf(&b, "%-24s file=%-24s wire=<%s> owner=%s\n", r.GoName, r.File, r.WireName, r.Owner)
		for _, c := range r.Consts {
			fmt.Fprintf(&b, "    %s\n", c)
		}
	}
	return b.String()
}
