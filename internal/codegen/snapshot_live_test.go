// The -gmp.* flags below mirror internal/gmptest's flags of the same name
// (see internal/gmptest/live.go) rather than importing that package for
// them: internal/gmptest also declares its own, unconditional -update flag
// (its derived-golden switch, see internal/gmptest/update.go), which would
// collide with this package's own -update the moment both are linked into
// one test binary — exactly the reason TestSnapshot's own update var is
// declared locally instead of reused from there (see its doc comment).
var (
	liveAddr = flag.String("gmp.addr", "127.0.0.1:9390",
		"host:port of gvmd's GMP TLS listener")
	liveUser = flag.String("gmp.user", "admin",
		"GMP username, as created by hack/gvmd-up.sh")
	livePass = flag.String("gmp.pass", "admin",
		"GMP password; matches hack/gvmd-up.sh's documented default")
	liveCAFile = flag.String("gmp.cafile", "../../hack/CA/cacert.pem",
		"path to the CA certificate generated by gvm-manage-certs (see hack/gvmd-up.sh)")
	liveServerName = flag.String("gmp.servername", "",
		"CN of gvmd's TLS server certificate, required unless -gmp.insecure is set; "+
			"note this can never verify against hack/gvmd-up.sh's certificates, which have no SAN — use -gmp.insecure for that stack")
	liveInsecure = flag.Bool("gmp.insecure", false,
		"skip TLS certificate verification instead of using -gmp.cafile/-gmp.servername; never the default, opt in explicitly")

	// liveComposeFile locates the stack backing the gvmd TestSnapshotLive
	// talks to, so dockerstack.ImageDigest can read its running image
	// digest for schema.LoadServed's provenance.
	liveComposeFile = flag.String("live.compose-file", "../../hack/docker-compose.yml",
		"path to the Compose file backing the live gvmd, used to resolve its image digest for schema.LoadServed's provenance")
)

// liveCommandTimeout bounds a single exchange once connected.
const liveCommandTimeout = 2 * time.Minute

// dialLive authenticates against a live gvmd and returns the connection,
// which the caller must Close.
//
// This deliberately dials and authenticates only — it does not wait for
// gvmd's feed sync the way internal/gmptest's WaitReady does for fixture
// capture. <help>'s output is the protocol's own command schema, not
// feed-derived data, so waiting up to 45 minutes for a feed sync here would
// cost real time for a check this path never needs.
func dialLive(ctx context.Context) (gmp.Connection, error) {
	var opts []connections.TLSOption
	if *liveInsecure {
		opts = []connections.TLSOption{connections.WithInsecureSkipVerify()}
	} else {
		if *liveServerName == "" {
			return nil, fmt.Errorf(
				"-gmp.servername is required unless -gmp.insecure is set (see -gmp.insecure's help text " +
					"for why hack/gvmd-up.sh's own certificates can never satisfy it)")
		}
		opts = []connections.TLSOption{
			connections.WithRootCAFile(*liveCAFile),
			connections.WithServerName(*liveServerName),
		}
	}

	conn, err := connections.NewTLSConnection(ctx, *liveAddr, opts...)
	if err != nil {
		return nil, fmt.Errorf("dialing gvmd: %w", err)
	}

	cli := client.New(conn)
	creds := &commands.AuthenticateCredentials{Username: *liveUser, Password: *livePass}
	if _, err := cli.Authenticate(ctx, &commands.Authenticate{Credentials: creds}); err != nil {
		_ = conn.Close()
		return nil, fmt.Errorf("authenticating: %w", err)
	}
	return conn, nil
}

// TestSnapshotLive is T-16b's served counterpart to TestSnapshot: its source
// is a live gvmd's own <help format="XML" type=""/> response instead of
// vendor/XML/commands. It writes straight to the same committed snapshotDir
// TestSnapshot does — parity between the two extraction paths was proven once
// (T-16b), so there is no separate live-only directory left to diff against.
// This is now the primary way to refresh testdata/schema/*.json.
//
//	go test -tags integration ./internal/codegen -run TestSnapshotLive -update \
//	  -gmp.addr=127.0.0.1:9390 -gmp.pass=… -gmp.servername=…
func TestSnapshotLive(t *testing.T) {
	if !*update {
		t.Skip("TestSnapshotLive only writes testdata/schema under -update; there is nothing to assert without it")
	}

	ctx, cancel := context.WithTimeout(context.Background(), liveCommandTimeout)
	defer cancel()

	conn, err := dialLive(ctx)
	if err != nil {
		t.Fatalf("connecting to gvmd: %v", err)
	}
	defer conn.Close()

	digest, err := dockerstack.ImageDigest(ctx, *liveComposeFile, "gvmd")
	if err != nil {
		t.Fatalf("resolving gvmd image digest: %v", err)
	}

	raw, err := conn.RawXML(ctx, `<help format="XML" type=""/>`)
	if err != nil {
		t.Fatalf("<help>: %v", err)
	}

	cmds, err := schema.LoadServed([]byte(raw), digest)
	if err != nil {
		t.Fatalf("LoadServed: %v", err)
	}

	byName := map[string]schema.Command{}
	for _, c := range cmds {
		byName[c.Name] = c
	}

	for _, name := range manifestOrFail(t).AllCommands() {
		cmd, ok := byName[name]
		if !ok {
			t.Fatalf("%s: not in the served schema", name)
		}
		writeMaskedSnapshot(t, SnapshotPath(snapshotDir, name), cmd)
	}
}

// writeMaskedSnapshot marshals cmd and writes it to path, reusing the
// committed bytes verbatim when the only difference is Provenance.ExtractedAt
// (stamped fresh on every run) — otherwise a no-op re-extraction would touch
// all 63 files and bury the one real change T-17 needs to be readable.
func writeMaskedSnapshot(t *testing.T, path string, cmd schema.Command) {
	t.Helper()

	got, err := MarshalSnapshot(cmd)
	if err != nil {
		t.Fatalf("%s: failed to marshal: %v", cmd.Name, err)
	}
	assertNoProse(t, cmd.Name, got)

	out := got
	if want, readErr := os.ReadFile(path); readErr == nil { //nolint:gosec // a fixed testdata path
		var wantCmd schema.Command
		if err := json.Unmarshal(want, &wantCmd); err != nil {
			t.Fatalf("%s: failed to parse the committed snapshot: %v", cmd.Name, err)
		}
		pinned := cmd
		pinned.Provenance.ExtractedAt = wantCmd.Provenance.ExtractedAt
		masked, err := MarshalSnapshot(pinned)
		if err != nil {
			t.Fatalf("%s: failed to marshal: %v", cmd.Name, err)
		}
		if string(masked) == string(want) {
			out = want
		}
	}

	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatalf("Failed to create %s: %v", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, out, 0o600); err != nil {
		t.Fatalf("Failed to write %s: %v", path, err)
	}
}
