//go:build integration

// Package gmptest also holds the live-gvmd readiness ladder in this file. It
// is compiled only with `-tags integration`; see live_test.go for the
// TestMain that runs it and hack/gvmd-up.sh for how
// to bring up something for it to poll.
//
// Nothing in this file has ever been run against a real gvmd — it is
// correct by construction against the documented protocol and the current
// client/connections signatures, but see the flag doc comments below for the
// one thing (the TLS server name) that can only be confirmed empirically.
package gmptest

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"time"

	gmp "github.com/brennoo/go-gmp"
	"github.com/brennoo/go-gmp/client"
	"github.com/brennoo/go-gmp/commands"
	"github.com/brennoo/go-gmp/connections"
)

// Flags controlling how the live suite reaches a real gvmd. Defaults match
// hack/gvmd-up.sh's own documented defaults, so
// `go test -tags integration ./internal/gmptest/...` works unmodified
// against a stack brought up with that script and no GVMD_ADMIN_PASSWORD
// override.
var (
	liveAddr = flag.String("gmp.addr", "127.0.0.1:9390",
		"host:port of gvmd's GMP TLS listener")
	liveUser = flag.String("gmp.user", "admin",
		"GMP username, as created by hack/gvmd-up.sh")
	livePass = flag.String("gmp.pass", "admin",
		"GMP password; matches hack/gvmd-up.sh's documented default, override to match GVMD_ADMIN_PASSWORD if that was set")
	liveCAFile = flag.String("gmp.cafile", "../../hack/CA/cacert.pem",
		"path to the CA certificate generated by gvm-manage-certs (see hack/gvmd-up.sh)")
	// liveServerName has no default on purpose, and in practice cannot be
	// made to work against a stack brought up by hack/gvmd-up.sh: confirmed
	// empirically, gvm-manage-certs' server certificate carries a CN but no
	// Subject Alternative Names at all, and Go's crypto/x509 refuses to fall
	// back to CN for hostname verification on a SAN-less certificate
	// ("certificate relies on legacy Common Name field, use SANs instead").
	// No CN value passed here can ever pass verification against that cert.
	// The flag stays required-unless-insecure anyway, so an operator with a
	// properly SAN'd certificate (a non-hack/ gvmd) can still use it;
	// dialOptions' error message below points -gmp.insecure at anyone
	// hitting the SAN-less case.
	liveServerName = flag.String("gmp.servername", "",
		"CN of gvmd's TLS server certificate, required unless -gmp.insecure is set; "+
			"note this can never verify against hack/gvmd-up.sh's certificates, which have no SAN — use -gmp.insecure for that stack")
	// liveInsecure must default to false: this is a security library, and an
	// escape hatch that verified nothing by default would defeat rung one of
	// the readiness ladder, which exists specifically to prove the
	// certificates are right.
	liveInsecure = flag.Bool("gmp.insecure", false,
		"skip TLS certificate verification instead of using -gmp.cafile/-gmp.servername; never the default, opt in explicitly")
)

const (
	// liveOverallBudget bounds the whole readiness ladder. A first boot's
	// feed sync has been observed to take 20-45 minutes; the budget leaves
	// headroom above that rather than cutting it close.
	liveOverallBudget = 60 * time.Minute
	// livePollInterval is how often the ladder is retried end to end.
	livePollInterval = 15 * time.Second
	// liveProgressInterval is how often a line is logged so a human watching
	// a cold boot can tell the ladder is still polling, not hung.
	liveProgressInterval = 30 * time.Second
)

// dialOptions builds the TLS options implied by the -gmp.* flags. Computed
// once per WaitReady call rather than per attempt, so a missing
// -gmp.servername fails immediately instead of after the first dial.
func dialOptions() ([]connections.TLSOption, error) {
	if *liveInsecure {
		return []connections.TLSOption{connections.WithInsecureSkipVerify()}, nil
	}
	if *liveServerName == "" {
		return nil, fmt.Errorf(
			"-gmp.servername is required unless -gmp.insecure is set: "+
				"note that against a hack/gvmd-up.sh stack no value here will work — "+
				"gvm-manage-certs' server certificate has no SAN at all, and Go refuses to "+
				"fall back to CN for hostname verification, so use -gmp.insecure instead; "+
				"-gmp.servername only helps against a server whose certificate has a real SAN "+
				"(find its CN with: openssl x509 -in %s -noout -subject)",
			*liveCAFile)
	}
	return []connections.TLSOption{
		connections.WithRootCAFile(*liveCAFile),
		connections.WithServerName(*liveServerName),
	}, nil
}

// ProgressFunc receives human-readable progress lines from WaitReady. A nil
// ProgressFunc is valid and discards them.
type ProgressFunc func(format string, args ...any)

// WaitReady polls a real gvmd through a readiness ladder and returns an
// authenticated client once every rung passes, or an error once
// liveOverallBudget elapses. The caller owns the returned gmp.Connection and
// must Close it.
//
// The ladder, from the least to the most specific claim it proves:
//
//  1. container running + TLS dial + <get_version/> succeeds — the only gate
//     that proves the generated certificates are trusted and gvmd's TLS
//     listener is actually up. A refused or reset dial means the container
//     is not there yet or is still starting.
//  2. <authenticate/> succeeds — kept separate from (1) because gvmd is
//     observed to serve get_version before user creation (by
//     hack/gvmd-up.sh, against Postgres directly) has fully settled into
//     the running daemon's view.
//  3. <get_feeds/> reports at least one feed, all with a non-empty <version>
//     and none with <currently_syncing> set — gvmd's own direct answer to
//     "has the 20-45 minute first-boot feed sync finished", which is the
//     actual long pole here and the reason the budget is an hour, not a
//     minute.
//
// Every attempt redials and reauthenticates from scratch rather than trying
// to keep a connection alive across the whole poll: at 15s intervals over up
// to an hour that is at most a few hundred reconnects against a local
// docker stack, and it avoids reasoning about whether a GMP session survives
// gvmd restarting mid-poll (restart: on-failure is set on every service in
// hack/docker-compose.yml).
func WaitReady(ctx context.Context, progress ProgressFunc) (gmp.Client, gmp.Connection, error) {
	if progress == nil {
		progress = func(string, ...any) {}
	}

	opts, err := dialOptions()
	if err != nil {
		return nil, nil, err
	}

	ctx, cancel := context.WithTimeout(ctx, liveOverallBudget)
	defer cancel()

	start := time.Now()
	nextProgress := start.Add(liveProgressInterval)

	var lastRung string
	var lastErr error

	for {
		cli, conn, rung, attemptErr := attemptReady(ctx, opts)
		if attemptErr == nil {
			progress("gvmd ready after %s", time.Since(start).Round(time.Second))
			return cli, conn, nil
		}
		if conn != nil {
			_ = conn.Close()
		}
		lastRung, lastErr = rung, attemptErr

		if now := time.Now(); !now.Before(nextProgress) {
			progress("still waiting for gvmd (stuck at %q after %s): %v",
				rung, now.Sub(start).Round(time.Second), attemptErr)
			nextProgress = now.Add(liveProgressInterval)
		}

		select {
		case <-ctx.Done():
			return nil, nil, fmt.Errorf(
				"gvmd not ready after %s budget (last failure at rung %q): %w: %w",
				liveOverallBudget, lastRung, ctx.Err(), lastErr)
		case <-time.After(livePollInterval):
		}
	}
}

// attemptReady runs the whole ladder once. On failure it returns the
// gmp.Connection dialed so far (or nil, if the dial itself failed) so the
// caller can close it, and the name of the rung that failed for progress
// reporting.
func attemptReady(ctx context.Context, opts []connections.TLSOption) (gmp.Client, gmp.Connection, string, error) {
	conn, err := connections.NewTLSConnection(ctx, *liveAddr, opts...)
	if err != nil {
		return nil, nil, "tls dial", err
	}
	cli := client.New(conn)

	if _, err := cli.GetVersion(ctx, &commands.GetVersion{}); err != nil {
		return nil, conn, "get_version", err
	}

	creds := commands.AuthCredentials{Username: *liveUser, Password: *livePass}
	if _, err := cli.Authenticate(ctx, &commands.Authenticate{Credentials: creds}); err != nil {
		return nil, conn, "authenticate", err
	}

	feeds, err := cli.GetFeeds(ctx, &commands.GetFeeds{})
	if err != nil {
		return nil, conn, "get_feeds", err
	}
	if err := feedsReady(feeds); err != nil {
		return nil, conn, "get_feeds (sync in progress)", err
	}

	return cli, conn, "ready", nil
}

// feedsReady reports nil once every feed gvmd knows about has a non-empty
// version and none are mid-sync — gvmd's direct answer to whether the
// first-boot feed sync has finished. An empty feed list is not ready: it
// means gvmd has not yet populated its feed table, which is itself early in
// the boot sequence.
func feedsReady(resp *commands.GetFeedsResponse) error {
	if resp == nil || len(resp.Feeds) == 0 {
		return errors.New("get_feeds returned no feeds yet")
	}
	for _, f := range resp.Feeds {
		if f.CurrentlySyncing != nil {
			return fmt.Errorf("feed %q is still syncing", f.Name)
		}
		if f.Version == "" {
			return fmt.Errorf("feed %q has no version yet", f.Name)
		}
	}
	return nil
}
